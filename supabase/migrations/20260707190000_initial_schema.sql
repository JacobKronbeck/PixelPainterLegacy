create or replace function delete_art_without_contributors()
returns trigger
language plpgsql
as $$
begin
  delete from art
  where id not in (select artid from contributingartists where artid is not null)
    and gifframenum <= 1;
  return null;
end;
$$;

drop trigger if exists contributingartist_delete_trigger on contributingartists;
create trigger contributingartist_delete_trigger
after delete on contributingartists
for each statement execute function delete_art_without_contributors();

create or replace function delete_orphaned_gif_frames()
returns trigger
language plpgsql
as $$
begin
  delete from art a
  where a.gifid in (
    select old_rows.gifid
    from old_rows
    where old_rows.gifid <> 0
  )
  and not exists (
    select 1
    from art remaining
    where remaining.gifid = a.gifid
      and remaining.gifframenum = 1
  );
  return null;
end;
$$;

drop trigger if exists gif_delete_trigger on art;
create trigger gif_delete_trigger
after delete on art
referencing old table as old_rows
for each statement execute function delete_orphaned_gif_frames();
